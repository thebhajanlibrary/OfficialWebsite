export const MONTH_NAMES = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];

export function localDateString(date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

/** Years from today onward that have calendar events. */
export function getCalendarYears(fromDate = new Date()): number[] {
  const currentYear = fromDate.getFullYear();
  const years = new Set<number>();
  for (const event of HINDU_CALENDAR_EVENTS) {
    if (event.year >= currentYear) {
      years.add(event.year);
    }
  }
  return Array.from(years).sort((a, b) => a - b);
}

/** Events for a year, from today forward (past dates hidden for the current year). */
export function getUpcomingEventsByYear(
  year: number,
  fromDate = new Date()
): CalendarEvent[] {
  const today = localDateString(fromDate);
  const currentYear = fromDate.getFullYear();

  return HINDU_CALENDAR_EVENTS.filter((event) => {
    if (event.year !== year) return false;
    if (year === currentYear) return event.date >= today;
    return year > currentYear;
  }).sort(
    (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
  );
}

export function getEventsByYear(year: number): CalendarEvent[] {
  return HINDU_CALENDAR_EVENTS.filter((e) => e.year === year).sort(
    (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
  );
}

export function groupEventsByMonth(
  events: CalendarEvent[]
): { monthIndex: number; monthName: string; events: CalendarEvent[] }[] {
  const map: Record<number, CalendarEvent[]> = {};
  for (const e of events) {
    if (!map[e.month]) {
      map[e.month] = [];
    }
    map[e.month].push(e);
  }

  const months = Object.keys(map)
    .map(Number)
    .sort((a, b) => a - b);

  return months.map((m) => ({
    monthIndex: m,
    monthName: MONTH_NAMES[m - 1],
    events: map[m].sort(
      (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
    ),
  }));
}
